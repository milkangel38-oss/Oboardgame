const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
export function themeHtml(game) {
  const t = THEMES[game.id];
  if (!t) return game.description ? `<p class="theme-story">${esc(game.description)}</p>` : '';
  const story = esc(t.story).replace(/\*\*(.+?)\*\*/g, '<em>$1</em>');
  return `<div class="theme-card">
    <div class="theme-title">${esc(t.title)}</div>
    <div class="theme-place">${esc(t.place)}</div>
    <p class="theme-story">${story}</p>
  </div>`;
}
