export const WORDS = (() => {
  const seen = new Set();
  const out = [];
  Object.values(RAW).forEach((line) => line.split(/\s+/).forEach((w) => {
    const [main, ...alias] = w.split('|');
    if (!main || seen.has(main)) return;
    seen.add(main);
    out.push({ word: main, alias });
  }));
  return out;
})();
